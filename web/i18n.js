  let curLang = "pt-BR";

  function resolveLang(lang) {
    if (!lang || lang === "auto") return "en-US";
    if (STRINGS[lang]) return lang;
    const low = String(lang).toLowerCase().replace("_", "-");
    for (const k of Object.keys(STRINGS)) {
      if (k.toLowerCase() === low) return k;
    }
    const base = low.split("-")[0];
    if (base === "pt") return "pt-BR";
    if (base === "zh") return low.includes("tw") || low.includes("hk") ? "zh-TW" : "zh-CN";
    if (base === "es") return low.includes("es") && !low.includes("la") ? "es-ES" : "es-LA";
    for (const k of Object.keys(STRINGS)) {
      if (k.toLowerCase().startsWith(base + "-")) return k;
    }
    return "en-US";
  }

